type outboundQueries interface {
	ListChatInputMessages(context.Context, pgtype.UUID) ([]db.ChatMessage, error)
	GetAgentTask(ctx context.Context, id pgtype.UUID) (db.AgentTaskQueue, error)
	TaskHasChannelIngestedMessages(ctx context.Context, taskID pgtype.UUID) (bool, error)
	GetChannelTaskDelivery(ctx context.Context, taskID pgtype.UUID) (db.ChannelTaskDelivery, error)
	GetChannelInstallation(ctx context.Context, arg db.GetChannelInstallationParams) (db.ChannelInstallation, error)
}

// Outbound delivers an agent's chat reply back to InfoFlow. It reads the same
// channel_task_delivery snapshot as Feishu/Slack/DingTalk and uses the binding
// config generated by the session resolver to choose a group or P2P target.
type Outbound struct {
	q       outboundQueries
	decrypt Decrypter
	client  *Client
	logger  *slog.Logger
}

func NewOutbound(q outboundQueries, decrypt Decrypter, client *Client, logger *slog.Logger) *Outbound {
	if logger == nil {
		logger = slog.Default()
	}
	if client == nil {
		client = NewClient(nil, "")
	}
	return &Outbound{q: q, decrypt: decrypt, client: client, logger: logger}
}

func (o *Outbound) Register(bus *events.Bus) {
	bus.Subscribe(protocol.EventChatDone, o.handleEvent)
	bus.Subscribe(protocol.EventTaskFailed, o.handleEvent)
	bus.Subscribe(protocol.EventTaskCancelled, o.handleEvent)
}

func (o *Outbound) handleEvent(e events.Event) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := o.processEvent(ctx, e); err != nil {
		if IsPermissionNotGranted(err) {
			o.logger.WarnContext(ctx, "infoflow outbound: permission not granted", "error", err)
			return
		}
		o.logger.WarnContext(ctx, "infoflow outbound: reply delivery failed", "error", err, "chat_session_id", e.ChatSessionID)
	}
}

func (o *Outbound) processEvent(ctx context.Context, e events.Event) error {
	taskID, sessionID, ok := taskAndSessionFromEvent(e)
	if !ok || !sessionID.Valid {
		return nil
	}
	content := eventContent(e)
	if content == "" && eventRetryPending(e) {
		return nil
	}
	if content == "" {
		return nil
	}
	delivery, err := o.q.GetChannelTaskDelivery(ctx, taskID)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil
		}
		return fmt.Errorf("lookup infoflow task delivery: %w", err)
	}
	if delivery.ChannelType != string(TypeInfoFlow) {
		return nil
	}
	binding := bindingFromTaskDelivery(delivery)
	task, err := o.q.GetAgentTask(ctx, taskID)
	if err != nil {
		return fmt.Errorf("load agent task: %w", err)
	}
	deliver, err := engine.TaskInputIsChannelIngested(ctx, o.q, task)
	if err != nil {
		return fmt.Errorf("classify task input origin: %w", err)
	}
	if !deliver {
		return nil
	}
	inst, err := o.q.GetChannelInstallation(ctx, db.GetChannelInstallationParams{
		ID: binding.InstallationID, ChannelType: string(TypeInfoFlow),
	})
	if err != nil {
		return fmt.Errorf("load infoflow installation: %w", err)
	}
	if inst.Status != "active" {
		return nil
	}
	creds, err := decodeCredentials(inst.Config, o.decrypt)
	if err != nil {
		return fmt.Errorf("decode infoflow credentials: %w", err)
	}
	s := &sender{client: o.client, appKey: creds.AppKey, appSecret: creds.AppSecret, agentID: creds.AgentID}
	target := outboundTarget(binding)
	_, sendErr := s.sendText(ctx, target, content)
	if sendErr == nil {
		return nil
	}
	// A single-chat reply depends on /app/message/send, which deployments may
	// not have been granted yet. That is a known capability gap, not a delivery
	// fault: log it once with actionable fields and drop the message instead of
	// retrying (a retry cannot succeed until the platform grants the API) or
	// escalating it to a generic failure that would page for every reply.
	if target.ChatType == string(channel.ChatTypeP2P) && IsPermissionNotGranted(sendErr) {
		o.logger.WarnContext(ctx, "infoflow outbound: single-chat reply skipped (application lacks /app/message/send)",
			"error", sendErr,
			"error_kind", "permission_not_granted",
			"installation_id", uuidOrEmpty(inst.ID),
			"chat_type", string(channel.ChatTypeP2P),
			"chat_id", target.ChatID,
			"action", "ask the InfoFlow admin to grant /app/message/send for this application",
		)
		return nil
	}
	return fmt.Errorf("post infoflow reply: %w", sendErr)
}

func bindingFromTaskDelivery(delivery db.ChannelTaskDelivery) db.ChannelChatSessionBinding {
	return db.ChannelChatSessionBinding{
		ID:             delivery.BindingID,
		InstallationID: delivery.InstallationID,
		ChannelType:    delivery.ChannelType,
		ChannelChatID:  delivery.ChannelChatID,
		ChatType:       delivery.ChatType,
		LastMessageID:  delivery.ChannelMessageID,
		LastThreadID:   delivery.ChannelThreadID,
		RouteRevision:  delivery.RouteRevision,
		Config:         delivery.Config,
	}
}

func eventRetryPending(e events.Event) bool {
	if e.Type != protocol.EventTaskFailed {
		return false
	}
	p, ok := e.Payload.(map[string]any)
	if !ok {
		return false
	}
	retryPending, _ := p["retry_pending"].(bool)
	return retryPending
}

func eventContent(e events.Event) string {
	switch p := e.Payload.(type) {
	case protocol.ChatDonePayload:
		return p.Content
	case map[string]any:
		if e.Type == protocol.EventTaskFailed {
			if retryPending, _ := p["retry_pending"].(bool); retryPending {
				return ""
			}
			if s, _ := p["error"].(string); s != "" {
				return "⚠️ " + s
			}
			return ""
		}
		if s, ok := p["content"].(string); ok {
			return s
		}
	}
	return ""
}

func taskAndSessionFromEvent(e events.Event) (taskID, sessionID pgtype.UUID, ok bool) {
	if e.TaskID != "" {
		_ = taskID.Scan(e.TaskID)
	}
	if e.ChatSessionID != "" {
		_ = sessionID.Scan(e.ChatSessionID)
	}
	switch p := e.Payload.(type) {
	case protocol.ChatDonePayload:
		if !taskID.Valid {
			_ = taskID.Scan(p.TaskID)
		}
		if !sessionID.Valid {
			_ = sessionID.Scan(p.ChatSessionID)
		}
	case map[string]any:
		if !taskID.Valid {
			if raw, _ := p["task_id"].(string); raw != "" {
				_ = taskID.Scan(raw)
			}
		}
		if !sessionID.Valid {
			if raw, _ := p["chat_session_id"].(string); raw != "" {
				_ = sessionID.Scan(raw)
			}
		}
	}
	return taskID, sessionID, taskID.Valid
}

